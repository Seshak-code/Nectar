//! The CUDA runtime's integrity check (INTEGRITY_CHECK in dark_api.rs). The runtime hashes
//! the same inputs itself and compares the answers.
//!
//! The algorithm and its test vectors are adapted from ZLUDA (dark_api/src/lib.rs,
//! https://github.com/vosen/ZLUDA, MIT; see LICENSE-ZLUDA). It is an HMAC over MD2: the
//! mixing table is MD2's substitution table, and the 0x36 and 0x5c passes are HMAC's inner
//! and outer pads, around a fixed key.

use std::ffi::c_void;

use nectar_cuda_sys::CUuuid;

/// What is hashed per device
#[repr(C)]
#[derive(Clone, Copy)]
pub(crate) struct DeviceHashInfo {
    pub guid: CUuuid,
    pub pci_domain: i32,
    pub pci_bus: i32,
    pub pci_device: i32,
}

#[repr(C)]
struct Pass3Input {
    driver_version: u32,
    version: u32,
    current_process: u32,
    current_thread: u32,
    cudart_table: *const c_void,
    integrity_check_table: *const c_void,
    fn_address: *const c_void,
    unix_seconds: u64,
}

/// The key, which the first pass would compute from no input
const KEY: [u8; 16] = [0x14, 0x6A, 0xDD, 0xAE, 0x53, 0xA9, 0xA7, 0x52, 0xAA, 0x08, 0x41, 0x36, 0x0B, 0xF5, 0x5A, 0x9F];

#[allow(clippy::too_many_arguments)]
pub(crate) fn compute(
    version: u32,
    unix_seconds: u64,
    driver_version: u32,
    current_process: u32,
    current_thread: u32,
    integrity_check_table: *const c_void,
    cudart_table: *const c_void,
    fn_address: *const c_void,
    devices: &[DeviceHashInfo],
) -> [u64; 2] {
    match version % 10 {
        0 => return [0x3341181C03CB675C, 0x8ED383AA1F4CD1E8],
        1 => return [0x1841181C03CB675C, 0x8ED383AA1F4CD1E8],
        _ => {}
    }

    let mut state = [0u8; 66];
    hash_pass(&mut state, &KEY, 0x36);
    let input = Pass3Input {
        driver_version,
        version,
        current_process,
        current_thread,
        cudart_table,
        integrity_check_table,
        fn_address,
        unix_seconds,
    };
    hash_pass(&mut state, &input, 0);
    for device in devices {
        hash_pass(&mut state, device, 0);
    }
    let inner = finish(&mut state);

    zero(&mut state);
    hash_pass(&mut state, &KEY, 0x5c);
    hash_pass(&mut state, &inner, 0);
    finish(&mut state)
}

fn zero(state: &mut [u8; 66]) {
    state[..16].fill(0);
    state[48..].fill(0);
}

/// Pads, mixes in the checksum and returns the digest
fn finish(state: &mut [u8; 66]) -> [u64; 2] {
    let padding = 16u8.wrapping_sub(state[64]);
    for _ in 0..padding {
        mix(state, padding);
    }
    for index in 0x30..0x40 {
        let byte = state[index];
        mix(state, byte);
    }
    [u64::from_ne_bytes(state[0..8].try_into().unwrap()), u64::from_ne_bytes(state[8..16].try_into().unwrap())]
}

fn hash_pass<T: Sized>(state: &mut [u8; 66], value: &T, xor_mask: u8) {
    let bytes = unsafe { std::slice::from_raw_parts((value as *const T).cast::<u8>(), size_of::<T>()) };
    for &byte in bytes {
        mix(state, byte ^ xor_mask);
    }
}

/// One byte into the MD2 state: 16 bytes of hash, 16 of block, 16 of scratch, 16 of checksum,
/// then the block position and the last checksum byte
fn mix(state: &mut [u8; 66], byte: u8) {
    const S: [u8; 256] = [
        0x29, 0x2E, 0x43, 0xC9, 0xA2, 0xD8, 0x7C, 0x01, 0x3D, 0x36, 0x54, 0xA1, 0xEC, 0xF0, 0x06, 0x13, 0x62, 0xA7, 0x05,
        0xF3, 0xC0, 0xC7, 0x73, 0x8C, 0x98, 0x93, 0x2B, 0xD9, 0xBC, 0x4C, 0x82, 0xCA, 0x1E, 0x9B, 0x57, 0x3C, 0xFD, 0xD4,
        0xE0, 0x16, 0x67, 0x42, 0x6F, 0x18, 0x8A, 0x17, 0xE5, 0x12, 0xBE, 0x4E, 0xC4, 0xD6, 0xDA, 0x9E, 0xDE, 0x49, 0xA0,
        0xFB, 0xF5, 0x8E, 0xBB, 0x2F, 0xEE, 0x7A, 0xA9, 0x68, 0x79, 0x91, 0x15, 0xB2, 0x07, 0x3F, 0x94, 0xC2, 0x10, 0x89,
        0x0B, 0x22, 0x5F, 0x21, 0x80, 0x7F, 0x5D, 0x9A, 0x5A, 0x90, 0x32, 0x27, 0x35, 0x3E, 0xCC, 0xE7, 0xBF, 0xF7, 0x97,
        0x03, 0xFF, 0x19, 0x30, 0xB3, 0x48, 0xA5, 0xB5, 0xD1, 0xD7, 0x5E, 0x92, 0x2A, 0xAC, 0x56, 0xAA, 0xC6, 0x4F, 0xB8,
        0x38, 0xD2, 0x96, 0xA4, 0x7D, 0xB6, 0x76, 0xFC, 0x6B, 0xE2, 0x9C, 0x74, 0x04, 0xF1, 0x45, 0x9D, 0x70, 0x59, 0x64,
        0x71, 0x87, 0x20, 0x86, 0x5B, 0xCF, 0x65, 0xE6, 0x2D, 0xA8, 0x02, 0x1B, 0x60, 0x25, 0xAD, 0xAE, 0xB0, 0xB9, 0xF6,
        0x1C, 0x46, 0x61, 0x69, 0x34, 0x40, 0x7E, 0x0F, 0x55, 0x47, 0xA3, 0x23, 0xDD, 0x51, 0xAF, 0x3A, 0xC3, 0x5C, 0xF9,
        0xCE, 0xBA, 0xC5, 0xEA, 0x26, 0x2C, 0x53, 0x0D, 0x6E, 0x85, 0x28, 0x84, 0x09, 0xD3, 0xDF, 0xCD, 0xF4, 0x41, 0x81,
        0x4D, 0x52, 0x6A, 0xDC, 0x37, 0xC8, 0x6C, 0xC1, 0xAB, 0xFA, 0x24, 0xE1, 0x7B, 0x08, 0x0C, 0xBD, 0xB1, 0x4A, 0x78,
        0x88, 0x95, 0x8B, 0xE3, 0x63, 0xE8, 0x6D, 0xE9, 0xCB, 0xD5, 0xFE, 0x3B, 0x00, 0x1D, 0x39, 0xF2, 0xEF, 0xB7, 0x0E,
        0x66, 0x58, 0xD0, 0xE4, 0xA6, 0x77, 0x72, 0xF8, 0xEB, 0x75, 0x4B, 0x0A, 0x31, 0x44, 0x50, 0xB4, 0x8F, 0xED, 0x1F,
        0x1A, 0xDB, 0x99, 0x8D, 0x33, 0x9F, 0x11, 0x83, 0x14,
    ];

    let position = state[0x40] as usize;
    state[position + 0x10] = byte;
    state[position + 0x20] = state[position] ^ byte;
    let checksum = S[(byte ^ state[0x41]) as usize] ^ state[position + 0x30];
    state[position + 0x30] = checksum;
    state[0x41] = checksum;

    let next = (position + 1) & 0xf;
    state[0x40] = next as u8;
    if next != 0 {
        return;
    }

    // A full block: 18 rounds over the 48 bytes of hash, block and scratch
    let mut t = 0u8;
    for round in 0..0x12u8 {
        for value in state[..0x30].iter_mut() {
            t = *value ^ S[t as usize];
            *value = t;
        }
        t = t.wrapping_add(round);
    }
}

