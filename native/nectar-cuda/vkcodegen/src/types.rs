//! Rust declarations of the Vulkan types and commands the registry requires: what
//! `vksys/src/generated.rs` holds.
//!
//! Every struct is `#[repr(C)]` with its members in order, so it has the C layout. Bitfields,
//! which only acceleration structure instances use, are packed into one u32 per 32 bits.
//! A type that depends on something the registry doesn't define (the video codec headers'
//! StdVideo types, for now) is left out, with what uses it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use crate::registry::{Decl, Registry, Type, Value};

/// C's own types, and the basetypes every Vulkan header defines the same way
pub fn c_type(name: &str) -> Option<&'static str> {
    Some(match name {
        "void" => "c_void",
        "char" => "c_char",
        "float" => "f32",
        "double" => "f64",
        "int8_t" => "i8",
        "uint8_t" => "u8",
        "int16_t" => "i16",
        "uint16_t" => "u16",
        "int32_t" => "i32",
        "uint32_t" => "u32",
        "int64_t" => "i64",
        "uint64_t" => "u64",
        "size_t" => "usize",
        "int" => "c_int",
        _ => return None,
    })
}

/// The types that can be declared: every member's type is known
pub struct Known<'a> {
    registry: &'a Registry,
    known: BTreeMap<String, bool>,
}

impl<'a> Known<'a> {
    pub fn new(registry: &'a Registry) -> Self {
        let mut known = Self { registry, known: BTreeMap::new() };
        for name in registry.required_types.clone() {
            known.check(&name, &mut BTreeSet::new());
        }
        known
    }

    pub fn is(&self, name: &str) -> bool {
        c_type(name).is_some() || self.known.get(name).copied().unwrap_or(false)
    }

    fn check(&mut self, name: &str, visiting: &mut BTreeSet<String>) -> bool {
        if c_type(name).is_some() {
            return true;
        }
        if let Some(&known) = self.known.get(name) {
            return known;
        }
        // A struct that points back to itself (through pNext-free links) is fine
        if !visiting.insert(name.to_string()) {
            return true;
        }
        let known = match self.registry.types.get(name) {
            None | Some(Type::External) => false,
            Some(Type::Alias(target)) => {
                let target = target.clone();
                self.check(&target, visiting)
            }
            Some(Type::Base(base)) => base.as_deref().is_some_and(|base| c_type(base).is_some()),
            Some(Type::Struct(s)) => {
                let members: Vec<String> = s.members.iter().map(|m| m.ty.clone()).collect();
                members.iter().all(|ty| self.check(ty, visiting))
            }
            Some(_) => true,
        };
        visiting.remove(name);
        self.known.insert(name.to_string(), known);
        known
    }

    /// Whether a command's return and parameter types can all be declared
    pub fn command(&self, name: &str) -> bool {
        self.registry.commands.get(name).is_some_and(|command| {
            self.is(command.ret.trim_end_matches('*'))
                && command.params.iter().all(|param| self.is(&param.ty))
        })
    }
}

/// A fixed array's size as a number
pub fn array_size(registry: &Registry, size: &str) -> usize {
    if let Ok(number) = size.parse() {
        return number;
    }
    match registry.constant(size) {
        Some(Value::Int(value)) => *value as usize,
        _ => panic!("unknown array size {size}"),
    }
}

/// The Rust type of a member or parameter
pub fn rust_type(registry: &Registry, decl: &Decl) -> String {
    let mut ty = c_type(&decl.ty).map(str::to_string).unwrap_or_else(|| decl.ty.clone());
    for &target_const in &decl.pointers {
        ty = format!("*{} {ty}", if target_const { "const" } else { "mut" });
    }
    for size in decl.array.iter().rev() {
        ty = format!("[{ty}; {}]", array_size(registry, size));
    }
    ty
}

fn base_rust(registry: &Registry, name: &str) -> String {
    match registry.types.get(name) {
        Some(Type::Base(Some(base))) => c_type(base).unwrap_or("u32").to_string(),
        _ => "u32".to_string(),
    }
}

/// `vksys/src/generated.rs`
pub fn emit(registry: &Registry, known: &Known) -> String {
    let mut out = String::from(
        "// Generated by nectar-vk-codegen from vk.xml; do not edit.\n\
         #![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]\n\n\
         use std::ffi::{c_char, c_int, c_void};\n\n",
    );

    out += "// API constants\n";
    for (name, value) in &registry.constants {
        let _ = match value {
            Value::Int(v) => writeln!(out, "pub const {name}: u32 = {};", *v as u32),
            Value::U64(v) => writeln!(out, "pub const {name}: u64 = {v};"),
            Value::Float(v) => writeln!(out, "pub const {name}: f32 = {v:?};"),
            Value::Text(_) => Ok(()),
        };
    }

    let mut types: Vec<&String> = registry.required_types.iter().filter(|t| known.is(t)).collect();
    types.sort();
    out += "\n// Types\n";
    for name in types {
        let Some(ty) = registry.types.get(name) else { continue };
        match ty {
            Type::External => {}
            Type::Alias(target) => {
                let _ = writeln!(out, "pub type {name} = {target};");
            }
            Type::Base(_) => {
                let _ = writeln!(out, "pub type {name} = {};", base_rust(registry, name));
            }
            Type::Handle { dispatchable: true } => {
                let _ = writeln!(
                    out,
                    "#[repr(C)]\npub struct {name}_T {{\n    _private: [u8; 0],\n}}\npub type {name} = *mut {name}_T;"
                );
            }
            Type::Handle { dispatchable: false } => {
                let _ = writeln!(out, "pub type {name} = u64;");
            }
            Type::Enum => {
                let group = registry.enums.get(name.as_str());
                let (bitmask, flags64) = group.map_or((false, false), |g| (g.bitmask, g.flags64));
                let repr = match (bitmask, flags64) {
                    (true, true) => "u64",
                    (true, false) => "u32",
                    _ => "i32",
                };
                let _ = writeln!(out, "pub type {name} = {repr};");
                if let Some(group) = group {
                    for (value_name, value) in &group.values {
                        let literal = match repr {
                            "u64" => format!("{:#x}", *value as u64),
                            "u32" => format!("{:#x}", *value as u32),
                            _ => value.to_string(),
                        };
                        let _ = writeln!(out, "pub const {value_name}: {name} = {literal};");
                    }
                }
            }
            Type::Bitmask { flags64, .. } => {
                let _ = writeln!(out, "pub type {name} = {};", if *flags64 { "u64" } else { "u32" });
            }
            Type::FuncPointer => {
                // Never called by Nectar; only its size matters
                let _ = writeln!(out, "pub type {name} = Option<unsafe extern \"system\" fn()>;");
            }
            Type::Struct(s) => emit_struct(&mut out, registry, name, s),
        }
    }

    out += "\n// Commands\n";
    for command in &registry.required_commands {
        if !known.command(command) {
            continue;
        }
        let command = &registry.commands[command];
        let params: Vec<String> = command
            .params
            .iter()
            .map(|p| format!("{}: {}", ident(&p.name), param_type(registry, p)))
            .collect();
        let ret = match command.ret.as_str() {
            "void" => String::new(),
            "PFN_vkVoidFunction" => " -> PFN_vkVoidFunction".to_string(),
            other => format!(" -> {}", c_type(other).unwrap_or(other)),
        };
        let _ = writeln!(
            out,
            "pub type PFN_{} = unsafe extern \"system\" fn({}){ret};",
            command.name,
            params.join(", ")
        );
    }
    out
}

fn emit_struct(out: &mut String, registry: &Registry, name: &str, s: &crate::registry::Struct) {
    let keyword = if s.union { "union" } else { "struct" };
    let _ = writeln!(out, "#[repr(C)]\n#[derive(Copy, Clone)]\npub {keyword} {name} {{");
    let mut bits: Option<(Vec<String>, u32)> = None;
    for member in &s.members {
        if let Some(width) = member.bitfield {
            let (names, used) = bits.get_or_insert_with(|| (Vec::new(), 0));
            names.push(member.name.clone());
            *used += width;
            if *used >= 32 {
                let _ = writeln!(out, "    pub {}: u32,", names.join("_and_"));
                bits = None;
            }
            continue;
        }
        let _ = writeln!(out, "    pub {}: {},", ident(&member.name), rust_type(registry, member));
    }
    out.push_str("}\n");
}

/// A name as a Rust identifier: C names that are Rust keywords get the raw prefix
pub fn ident(name: &str) -> String {
    match name {
        "type" | "match" | "fn" | "struct" | "enum" | "impl" | "loop" | "move" | "ref" | "self"
        | "use" | "where" | "mod" | "box" | "in" | "async" | "await" | "dyn" => format!("r#{name}"),
        _ => name.to_string(),
    }
}

/// The Rust type of a command parameter: a C array parameter is a pointer to its first element
pub fn param_type(registry: &Registry, decl: &Decl) -> String {
    if decl.array.is_empty() {
        return rust_type(registry, decl);
    }
    let element = Decl { array: Vec::new(), ..decl.clone() };
    format!("*{} {}", if decl.inner_const { "const" } else { "mut" }, rust_type(registry, &element))
}
